export const TECHS = {};
function T(id, name, cat, year, cost, req, eff, desc) {
  TECHS[id] = { id, name, cat, year, cost, req: req || [], ...(eff || {}), desc: desc || '' };
}
function chain(prefix, name, cat, years, cost, effFn, descFn) {
  const R = ['', 'I', 'II', 'III', 'IV', 'V'];
  years.forEach((y, i) => {
    const lvl = i + 1;
    T(prefix + lvl, `${name} ${R[lvl]}`, cat, y, cost + i * 20, lvl > 1 ? [prefix + (lvl - 1)] : [], effFn(lvl), descFn ? descFn(lvl) : '');
  });
}

